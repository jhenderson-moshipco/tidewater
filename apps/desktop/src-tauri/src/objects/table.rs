    #[test]
    fn indexes_are_rebuilt_when_changed_renamed_when_only_renamed_and_built_concurrently_after_the_commit() {
        let mut before = orders();
        before.indexes.extend([index(Some("by_quantity"), "by_quantity", "quantity"), index(Some("stale"), "stale", "id")]);
        let mut after = before.clone();
        after.name = "items".into();
        after.schema = "sales".into();
        after.indexes[0].clauses = "WHERE note <> ''".into();
        after.indexes[1].name = "quantity_idx".into();
        after.indexes[2].keys = "id DESC".into();
        after.indexes[2].concurrently = true;
        after.indexes.push(IndexDefinition { concurrently: true, ..index(None, "", "note, quantity") });

        let planned = alter(&before, &after, options()).unwrap();

        assert_eq!(planned.statements, [
            "DROP INDEX public.order_items_note",
            "DROP INDEX public.stale",
            "ALTER INDEX public.by_quantity RENAME TO quantity_idx",
            "CREATE INDEX order_items_note ON public.order_items USING btree (note) WHERE note <> ''",
        ]);
        assert_eq!(planned.after_commit, [
            "CREATE INDEX CONCURRENTLY stale ON sales.items USING btree (id DESC)",
            "CREATE INDEX CONCURRENTLY ON sales.items USING btree (note, quantity)",
        ]);
        assert_eq!(titles(&planned), ["Writes wait while indexes build", "Builds indexes after the commit"]);
        assert_eq!(
            planned.warnings[1].detail,
            "stale and the new index build concurrently, each on its own once the rest of the change commits. If one fails, the \
             rest of the change stays, and the failed build leaves an invalid index to drop."
        );
    }

