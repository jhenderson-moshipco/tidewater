//! Writes the DDL that creates a table or changes its columns, constraints and indexes. Nothing here touches a database.

use std::collections::HashMap;

use super::ddl::{Planned, comment_on, ident, qualified, required, warning};
use super::model::{ChangeOptions, ColumnDefinition, ConstraintDefinition, ConstraintKind, Identity, IndexDefinition, ReferentialAction, TableDefinition};
use crate::error::CommandError;

fn invalid(message: String) -> CommandError {
    CommandError::Invalid(message)
}

/// The names in a list typed or picked in the designer, without blanks or the space around them.
fn trimmed(list: &[String]) -> Vec<&str> {
    list.iter().map(|name| name.trim()).filter(|name| !name.is_empty()).collect()
}

fn names(list: &[String]) -> String {
    trimmed(list).into_iter().map(ident).collect::<Vec<_>>().join(", ")
}

/// A list as a sentence names it: `a`, `a and b`, `a, b and c`.
fn spoken(list: &[String]) -> String {
    match list {
        [] => String::new(),
        [only] => only.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    }
}

fn referential(action: ReferentialAction) -> &'static str {
    match action {
        ReferentialAction::NoAction => "NO ACTION",
        ReferentialAction::Restrict => "RESTRICT",
        ReferentialAction::Cascade => "CASCADE",
        ReferentialAction::SetNull => "SET NULL",
        ReferentialAction::SetDefault => "SET DEFAULT",
    }
}

fn column_sql(column: &ColumnDefinition) -> String {
    let mut parts = vec![ident(&column.name), column.data_type.clone()];
    if !column.generated.is_empty() {
        parts.push(format!("GENERATED ALWAYS AS ({}) STORED", column.generated));
    }
    match column.identity {
        Identity::Always => parts.push("GENERATED ALWAYS AS IDENTITY".into()),
        Identity::ByDefault => parts.push("GENERATED BY DEFAULT AS IDENTITY".into()),
        Identity::None => {}
    }
    if column.not_null {
        parts.push("NOT NULL".into());
    }
    if !column.default.is_empty() {
        parts.push(format!("DEFAULT {}", column.default));
    }
    parts.join(" ")
}

fn constraint_body(constraint: &ConstraintDefinition) -> String {
    match constraint.kind {
        ConstraintKind::PrimaryKey => format!("PRIMARY KEY ({})", names(&constraint.columns)),
        ConstraintKind::Unique => format!("UNIQUE ({})", names(&constraint.columns)),
        ConstraintKind::ForeignKey => {
            let mut sql = format!("FOREIGN KEY ({}) REFERENCES {}", names(&constraint.columns), constraint.references);
            if !trimmed(&constraint.referenced_columns).is_empty() {
                sql.push_str(&format!(" ({})", names(&constraint.referenced_columns)));
            }
            for (clause, action) in [("ON UPDATE", constraint.on_update), ("ON DELETE", constraint.on_delete)] {
                if action != ReferentialAction::NoAction {
                    sql.push_str(&format!(" {clause} {}", referential(action)));
                }
            }
            sql
        }
        ConstraintKind::Check => format!("CHECK ({})", constraint.expression),
        ConstraintKind::Other => constraint.expression.clone(),
    }
}

fn constraint_sql(constraint: &ConstraintDefinition) -> String {
    if constraint.name.is_empty() {
        return constraint_body(constraint);
    }
    format!("CONSTRAINT {} {}", ident(&constraint.name), constraint_body(constraint))
}

/// Whether existing rows are checked when the constraint is added: `NOT VALID` only skips that for foreign keys and checks.
fn checks_rows(constraint: &ConstraintDefinition) -> bool {
    let skippable = (constraint.kind == ConstraintKind::ForeignKey) | (constraint.kind == ConstraintKind::Check);
    !(constraint.not_valid & skippable)
}

fn index_sql(index: &IndexDefinition, table: &str, concurrently: bool) -> String {
    let unique = if index.unique { "UNIQUE " } else { "" };
    let concurrently = if concurrently { "CONCURRENTLY " } else { "" };
    let name = if index.name.is_empty() { String::new() } else { format!("{} ", ident(&index.name)) };
    let clauses = index.clauses.trim();
    let clauses = if clauses.is_empty() { String::new() } else { format!(" {clauses}") };
    format!("CREATE {unique}INDEX {concurrently}{name}ON {table} USING {} ({}){clauses}", index.method, index.keys)
}

fn validate_column(column: &ColumnDefinition, seen: &mut Vec<String>) -> Result<(), CommandError> {
    required(&column.name, "Each column's name")?;
    if column.data_type.trim().is_empty() {
        return Err(invalid(format!("Column {} needs a type.", column.name)));
    }
    if seen.contains(&column.name) {
        return Err(invalid(format!("Two columns are named {}.", column.name)));
    }
    seen.push(column.name.clone());
    let identity = column.identity != Identity::None;
    if !column.generated.is_empty() && (identity || !column.default.is_empty()) {
        return Err(invalid(format!("Column {} is generated, so it can't have a default or be an identity column.", column.name)));
    }
    if identity && !column.default.is_empty() {
        return Err(invalid(format!("Column {} is an identity column, so it can't have a default.", column.name)));
    }
    Ok(())
}

fn validate_constraint(constraint: &ConstraintDefinition) -> Result<(), CommandError> {
    if constraint.original_name.is_some() && constraint.name.trim().is_empty() {
        return Err(invalid("An existing constraint needs a name.".into()));
    }
    let needs_columns = matches!(constraint.kind, ConstraintKind::PrimaryKey | ConstraintKind::Unique | ConstraintKind::ForeignKey);
    if needs_columns && trimmed(&constraint.columns).is_empty() {
        return Err(invalid("Primary keys, unique constraints and foreign keys need at least one column.".into()));
    }
    if constraint.kind == ConstraintKind::ForeignKey {
        required(&constraint.references, "The table a foreign key references")?;
        let referenced = trimmed(&constraint.referenced_columns).len();
        if referenced != 0 && referenced != trimmed(&constraint.columns).len() {
            return Err(invalid("A foreign key needs as many referenced columns as columns, or none for the primary key.".into()));
        }
    }
    if matches!(constraint.kind, ConstraintKind::Check | ConstraintKind::Other) {
        required(&constraint.expression, "A check's expression")?;
    }
    Ok(())
}

pub fn validate(table: &TableDefinition) -> Result<(), CommandError> {
    required(&table.schema, "Schema")?;
    required(&table.name, "Name")?;
    let mut seen = Vec::new();
    for column in &table.columns {
        validate_column(column, &mut seen)?;
    }
    if table.constraints.iter().filter(|constraint| constraint.kind == ConstraintKind::PrimaryKey).count() > 1 {
        return Err(invalid("A table can have only one primary key.".into()));
    }
    for constraint in &table.constraints {
        validate_constraint(constraint)?;
    }
    for index in &table.indexes {
        if index.original_name.is_some() && index.name.trim().is_empty() {
            return Err(invalid("An existing index needs a name.".into()));
        }
        required(&index.method, "Each index's method")?;
        required(&index.keys, "Each index's columns")?;
    }
    Ok(())
}

/// The `CREATE TABLE` statement, with every column and constraint.
pub fn create_statement(table: &TableDefinition) -> String {
    let lines: Vec<String> = table.columns.iter().map(column_sql).chain(table.constraints.iter().map(constraint_sql)).collect();
    format!("CREATE TABLE {} (\n  {}\n)", qualified(&table.schema, &table.name), lines.join(",\n  "))
}

/// What follows `CREATE TABLE` and the table's comment: its indexes and its columns' comments. A new table is empty, so
/// its indexes build in the transaction even when marked concurrent.
pub fn after_create(table: &TableDefinition) -> Vec<String> {
    let target = qualified(&table.schema, &table.name);
    let mut statements: Vec<String> = table.indexes.iter().map(|index| index_sql(index, &target, false)).collect();
    for column in table.columns.iter().filter(|column| column.comment.as_deref().is_some_and(|text| !text.is_empty())) {
        statements.push(comment_on(&format!("COLUMN {target}.{}", ident(&column.name)), &column.comment));
    }
    statements
}

/// What a change to existing rows risks, gathered so each warning names every column or constraint it covers.
#[derive(Default)]
struct Risks {
    rewritten: Vec<String>,
    set_not_null: Vec<String>,
    added_not_null: Vec<String>,
    dropped: Vec<String>,
    checked: Vec<String>,
    keyed: Vec<String>,
    indexed: Vec<String>,
    concurrent: Vec<String>,
}

impl Risks {
    fn warnings(&self, table: &str, cascade: bool) -> Vec<super::model::ChangeWarning> {
        let mut warnings = Vec::new();
        let mut add = |subjects: &Vec<String>, title: &str, detail: &dyn Fn(String) -> String| {
            if !subjects.is_empty() {
                warnings.push(warning(title, detail(spoken(subjects))));
            }
        };
        add(&self.rewritten, "ACCESS EXCLUSIVE lock, may rewrite the table", &|columns| {
            format!("Changing the type of {columns} can rewrite {table} and its indexes. Reads and writes wait until it finishes.")
        });
        add(&self.set_not_null, "Checks every row", &|columns| {
            format!("Making {columns} NOT NULL scans {table} while reads and writes wait, and fails if a row has no value.")
        });
        add(&self.added_not_null, "Fails if the table has rows", &|columns| {
            format!("{columns} is NOT NULL with no default, so adding it fails unless {table} is empty.")
        });
        add(&self.dropped, "Deletes data", &|columns| format!("Dropping {columns} deletes the values stored in it."));
        add(&self.checked, "Checks existing rows", &|constraints| {
            format!("Adding {constraints} checks every row of {table} while writes wait. NOT VALID skips the check.")
        });
        add(&self.keyed, "Builds an index", &|constraints| format!("Adding {constraints} builds its index while writes to {table} wait."));
        add(&self.indexed, "Writes wait while indexes build", &|indexes| {
            format!("Building {indexes} holds a SHARE lock on {table}: reads go on, writes wait. Concurrently avoids that.")
        });
        add(&self.concurrent, "Builds indexes after the commit", &|indexes| {
            format!(
                "{indexes} build concurrently, each on its own once the rest of the change commits. If one fails, the rest of the \
                 change stays, and the failed build leaves an invalid index to drop."
            )
        });
        if cascade {
            warnings.push(warning("Drops dependents too", "CASCADE also drops every object listed as depending on what is dropped."));
        }
        warnings
    }
}

fn label(name: &str, fallback: &str) -> String {
    if name.is_empty() { fallback.to_string() } else { name.to_string() }
}

/// Pairs each changed item with the original it came from, by `key`, and lists the originals no longer there.
fn matched<'a, T, K: Eq + std::hash::Hash>(
    original: &'a [T],
    changed: &'a [T],
    key: impl Fn(&T) -> Option<K>,
) -> (Vec<(Option<&'a T>, &'a T)>, Vec<&'a T>) {
    let by_key: HashMap<K, &T> = original.iter().filter_map(|item| key(item).map(|found| (found, item))).collect();
    let pairs: Vec<(Option<&T>, &T)> = changed.iter().map(|item| (key(item).and_then(|found| by_key.get(&found).copied()), item)).collect();
    let kept: Vec<K> = changed.iter().filter_map(&key).collect();
    let removed = original.iter().filter(|item| key(item).is_none_or(|found| !kept.contains(&found))).collect();
    (pairs, removed)
}

/// Whether a constraint is unchanged, reading `original`'s columns under the names `renamed` gives them, since renaming
/// a column renames it in its constraints too.
fn same_constraint(original: &ConstraintDefinition, changed: &ConstraintDefinition, renamed: &HashMap<&str, &str>) -> bool {
    let columns: Vec<&str> = trimmed(&original.columns).into_iter().map(|name| renamed.get(name).copied().unwrap_or(name)).collect();
    let referenced = (trimmed(&original.referenced_columns), trimmed(&changed.referenced_columns));
    (original.kind, columns, &original.references, referenced.0, original.on_update, original.on_delete, &original.expression)
        == (changed.kind, trimmed(&changed.columns), &changed.references, referenced.1, changed.on_update, changed.on_delete, &changed.expression)
}

fn same_index(left: &IndexDefinition, right: &IndexDefinition) -> bool {
    (left.unique, &left.method, &left.keys, left.clauses.trim()) == (right.unique, &right.method, &right.keys, right.clauses.trim())
}

/// The `ALTER COLUMN` actions that bring an existing column from `before` to `after`, which is already renamed.
fn column_actions(before: &ColumnDefinition, after: &ColumnDefinition, risks: &mut Risks) -> Result<Vec<String>, CommandError> {
    if before.generated != after.generated {
        return Err(invalid(format!("The expression of generated column {} can't change. Drop the column and add it again.", before.name)));
    }
    let column = ident(&after.name);
    let mut actions = Vec::new();
    if before.data_type != after.data_type {
        let using = if after.using.trim().is_empty() { String::new() } else { format!(" USING {}", after.using.trim()) };
        actions.push(format!("ALTER COLUMN {column} TYPE {}{using}", after.data_type));
        risks.rewritten.push(after.name.clone());
    }
    if before.default != after.default {
        actions.push(if after.default.is_empty() { format!("ALTER COLUMN {column} DROP DEFAULT") } else { format!("ALTER COLUMN {column} SET DEFAULT {}", after.default) });
    }
    if before.not_null != after.not_null {
        actions.push(format!("ALTER COLUMN {column} {} NOT NULL", if after.not_null { "SET" } else { "DROP" }));
        if after.not_null {
            risks.set_not_null.push(after.name.clone());
        }
    }
    if before.identity != after.identity {
        actions.push(match (before.identity, after.identity) {
            (_, Identity::None) => format!("ALTER COLUMN {column} DROP IDENTITY"),
            (Identity::None, Identity::Always) => format!("ALTER COLUMN {column} ADD GENERATED ALWAYS AS IDENTITY"),
            (Identity::None, Identity::ByDefault) => format!("ALTER COLUMN {column} ADD GENERATED BY DEFAULT AS IDENTITY"),
            (_, Identity::Always) => format!("ALTER COLUMN {column} SET GENERATED ALWAYS"),
            (_, Identity::ByDefault) => format!("ALTER COLUMN {column} SET GENERATED BY DEFAULT"),
        });
    }
    Ok(actions)
}

/// The DDL that changes `before` into `after`, except a new name, schema or table comment, which the caller adds.
/// Everything runs against the table's original name; concurrent index builds, which come after, use its new one.
pub fn alter(before: &TableDefinition, after: &TableDefinition, options: ChangeOptions) -> Result<Planned, CommandError> {
    let table = qualified(&before.schema, &before.name);
    let cascade = if options.cascade { " CASCADE" } else { "" };
    let mut risks = Risks::default();
    let mut planned = Planned::default();
    let mut renames = Vec::new();
    let mut actions = Vec::new();

    let (columns, dropped_columns) = matched(&before.columns, &after.columns, |column| column.number);
    let (constraints, dropped_constraints) = matched(&before.constraints, &after.constraints, |constraint| constraint.original_name.clone());
    let (indexes, dropped_indexes) = matched(&before.indexes, &after.indexes, |index| index.original_name.clone());
    let renamed: HashMap<&str, &str> =
        columns.iter().filter_map(|(original, column)| original.map(|original| (original.name.as_str(), column.name.as_str()))).collect();

    for (original, index) in &indexes {
        if let Some(original) = original.filter(|original| !same_index(original, index)) {
            planned.statements.push(format!("DROP INDEX {}{cascade}", qualified(&before.schema, &original.name)));
        }
    }
    for index in &dropped_indexes {
        planned.statements.push(format!("DROP INDEX {}{cascade}", qualified(&before.schema, &index.name)));
    }

    let mut added_constraints = Vec::new();
    let mut validated = Vec::new();
    for (original, constraint) in &constraints {
        match original {
            Some(original) if !same_constraint(original, constraint, &renamed) => {
                actions.push(format!("DROP CONSTRAINT {}{cascade}", ident(&original.name)));
                planned.dropped_constraints.push(original.name.clone());
                added_constraints.push(*constraint);
            }
            Some(original) => {
                if original.name != constraint.name {
                    renames.push(format!("ALTER TABLE {table} RENAME CONSTRAINT {} TO {}", ident(&original.name), ident(&constraint.name)));
                }
                if original.not_valid && !constraint.not_valid {
                    validated.push(*constraint);
                }
            }
            None => added_constraints.push(*constraint),
        }
    }
    for constraint in &dropped_constraints {
        actions.push(format!("DROP CONSTRAINT {}{cascade}", ident(&constraint.name)));
        planned.dropped_constraints.push(constraint.name.clone());
    }

    for column in &dropped_columns {
        actions.push(format!("DROP COLUMN {}{cascade}", ident(&column.name)));
        planned.dropped_columns.push(column.number.unwrap_or_default());
        risks.dropped.push(column.name.clone());
    }
    let mut comments = Vec::new();
    for (original, column) in &columns {
        match original {
            Some(original) => {
                if original.name != column.name {
                    renames.push(format!("ALTER TABLE {table} RENAME COLUMN {} TO {}", ident(&original.name), ident(&column.name)));
                }
                actions.extend(column_actions(original, column, &mut risks)?);
                if original.comment != column.comment {
                    comments.push(comment_on(&format!("COLUMN {table}.{}", ident(&column.name)), &column.comment));
                }
            }
            None => {
                actions.push(format!("ADD COLUMN {}", column_sql(column)));
                let filled = !column.default.is_empty() || column.identity != Identity::None || !column.generated.is_empty();
                if column.not_null && !filled {
                    risks.added_not_null.push(column.name.clone());
                }
                if column.comment.as_deref().is_some_and(|text| !text.is_empty()) {
                    comments.push(comment_on(&format!("COLUMN {table}.{}", ident(&column.name)), &column.comment));
                }
            }
        }
    }

    for constraint in added_constraints {
        let not_valid = if checks_rows(constraint) { "" } else { " NOT VALID" };
        actions.push(format!("ADD {}{not_valid}", constraint_sql(constraint)));
        let subject = label(&constraint.name, "the new constraint");
        match constraint.kind {
            ConstraintKind::PrimaryKey | ConstraintKind::Unique => risks.keyed.push(subject),
            ConstraintKind::ForeignKey | ConstraintKind::Check if checks_rows(constraint) => risks.checked.push(subject),
            _ => {}
        }
    }
    for constraint in validated {
        actions.push(format!("VALIDATE CONSTRAINT {}", ident(&constraint.name)));
        risks.checked.push(constraint.name.clone());
    }

    planned.statements.extend(renames);
    for (original, index) in &indexes {
        if let Some(original) = original.filter(|original| same_index(original, index) && original.name != index.name) {
            planned.statements.push(format!("ALTER INDEX {} RENAME TO {}", qualified(&before.schema, &original.name), ident(&index.name)));
        }
    }
    if !actions.is_empty() {
        planned.statements.push(format!("ALTER TABLE {table}\n  {}", actions.join(",\n  ")));
    }
    let moved = qualified(&after.schema, &after.name);
    for (original, index) in &indexes {
        if original.is_some_and(|original| same_index(original, index)) {
            continue;
        }
        let subject = label(&index.name, "the new index");
        if index.concurrently {
            planned.after_commit.push(index_sql(index, &moved, true));
            risks.concurrent.push(subject);
        } else {
            planned.statements.push(index_sql(index, &table, false));
            risks.indexed.push(subject);
        }
    }
    planned.statements.extend(comments);
    let drops = !dropped_columns.is_empty() | !planned.dropped_constraints.is_empty() | !dropped_indexes.is_empty();
    planned.warnings = risks.warnings(&table, options.cascade & drops);
    Ok(planned)
}

