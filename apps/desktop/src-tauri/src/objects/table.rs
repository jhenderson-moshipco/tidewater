    #[test]
    fn a_changed_constraint_is_dropped_and_added_while_a_renamed_one_is_only_renamed() {
        let mut before = orders();
        let mut check = constraint(Some("positive"), "positive", ConstraintKind::Check, &[]);
        check.expression = "quantity > 0".into();
        check.not_valid = true;
        let mut key = constraint(Some("order_fk"), "order_fk", ConstraintKind::ForeignKey, &["quantity"]);
        key.references = "orders".into();
        before.constraints.extend([check, key.clone(), constraint(Some("gone"), "gone", ConstraintKind::Unique, &["note"])]);
        let mut after = before.clone();
        after.constraints[0].columns = vec!["id".into(), "quantity".into()];
        after.constraints[1].name = "quantity_positive".into();
        after.constraints[1].not_valid = false;
        after.constraints[2].on_delete = ReferentialAction::Cascade;
        after.constraints[2].not_valid = true;
        after.constraints.pop();
        after.constraints.push(constraint(None, "", ConstraintKind::Unique, &["note"]));

        let planned = alter(&before, &after, options()).unwrap();

        assert_eq!(planned.statements, [
            "ALTER TABLE public.order_items RENAME CONSTRAINT positive TO quantity_positive",
            "ALTER TABLE public.order_items\n  DROP CONSTRAINT order_items_pkey,\n  DROP CONSTRAINT order_fk,\n  DROP CONSTRAINT gone,\n  \
             ADD CONSTRAINT order_items_pkey PRIMARY KEY (id, quantity),\n  \
             ADD CONSTRAINT order_fk FOREIGN KEY (quantity) REFERENCES orders ON DELETE CASCADE NOT VALID,\n  ADD UNIQUE (note),\n  \
             VALIDATE CONSTRAINT quantity_positive",
        ]);
        assert_eq!(planned.dropped_constraints, ["order_items_pkey", "order_fk", "gone"]);
        assert_eq!(titles(&planned), ["Checks existing rows", "Builds an index"]);
        assert_eq!(planned.warnings[1].detail, "Adding order_items_pkey and the new constraint builds its index while writes to public.order_items wait.");
    }

